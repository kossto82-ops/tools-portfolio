export function t(lang: Language, key: keyof typeof translations.en, params?: Record<string, string | number>): string {
  const dict = translations[lang] || translations.en;
  let str = (dict[key] as string) || (translations.en[key] as string) || String(key);

  if (params) {
    Object.entries(params).forEach(([paramKey, paramVal]) => {
      str = str.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramVal));
    });
  }

  return str;
}
